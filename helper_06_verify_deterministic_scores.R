Rcpp::sourceCpp('06_coexistence_hdr_scores.cpp',cacheDir='coexistence_cpp_cache')
Rcpp::sourceCpp('helper_06_reference_hdr_scores.cpp',cacheDir='coexistence_reference_cpp_cache')
source('05_random_allocation_reference.R')
set.seed(106);n<-24L
b1<-runif(n,.02,.98);b2<-runif(n,.02,.98);p1<-runif(n,.1,3.1);p2<-runif(n,.1,3.1)
b1[1:6]<-c(.1,.5,.9,.9,.5,.1);b2[1:6]<-c(.1,.5,.9,.5,.9,.9)
p1[1:6]<-c(.66,1,3.1,1.5,3.1,.1);p2[1:6]<-c(1.5,1,2.5,.66,.1,3.1)
rho<-vapply(1:n,function(k)random_allocation_reference(b1[k],b2[k],p1[k],p2[k])$s,1)
B<-50;s<-sqrt(log((1+sqrt(2))/2));hc<- -s^2;hr<-s*sqrt(qchisq(.99,2,ncp=2*s^2))
u<-seq(0,1,length.out=101);xt<-sort(unique(c(seq(0,B,length.out=181),B*u^2/2,B-B*u^2/2)))
args<-list(b1,b2,p1,p2,rho,xt,seq(0,25,length.out=121),seq(25,50,length.out=121),seq(-pi/2,pi/2,length.out=61),hc,hr,B,3)
new<-do.call(coexistence_scores_cpp,args);old<-do.call(coexistence_reference_scores_cpp,args)
err<-sapply(names(new),function(k)max(abs(pmax(0,new[[k]])-pmax(0,old[[k]]))))
print(err)
for(k in seq_along(new))stopifnot(all((new[[k]]>c(0,1e-4,1e-4,0)[k])==(old[[k]]>c(0,1e-4,1e-4,0)[k])))
stopifnot(max(err)<3e-4)
saveRDS(list(beta1=b1,beta2=b2,phi1=p1,phi2=p2,rho=rho,new=new,reference=old,positive_score_error=err),'06_coexistence_score_verification.rds')
cat('Endpoint-corrected global-search comparison passed.\n')

# Independent analytic checks for symmetric linear-spoils tournaments.
beta<-c(.1,.5,.9)
a<-list(beta,beta,rep(1,3),rep(1,3),rep(1,3),xt,seq(0,25,length.out=121),seq(25,50,length.out=121),seq(-pi/2,pi/2,length.out=61),hc,hr,B,3)
z<-do.call(coexistence_scores_cpp,a)
sm<-hr*sqrt(2)-(1-beta)*log1p(B)
sd<-pmin(hr*sqrt(2),(1-beta)*log1p(B))
stopifnot(max(abs(z$S2max-sm),abs(z$S1max-sm),abs(z$S2div-sd),abs(z$S1div-sd))<1e-6)
# Increase talent-slice and allocation-search resolution independently.
a<-args;a[[6]]<-sort(unique(c(seq(0,B,length.out=361),B*seq(0,1,length.out=201)^2/2,B-B*seq(0,1,length.out=201)^2/2)))
a[[7]]<-seq(0,25,length.out=241);a[[8]]<-seq(25,50,length.out=241);a[[9]]<-seq(-pi/2,pi/2,length.out=121)
fine<-do.call(coexistence_scores_cpp,a)
resolution_error<-sapply(names(new),function(k)max(abs(pmax(0,new[[k]])-pmax(0,fine[[k]]))))
print(resolution_error);stopifnot(max(resolution_error)<5e-4)
saveRDS(list(reference_comparison=readRDS('06_coexistence_score_verification.rds'),linear_analytic=list(beta=beta,sm=sm,sd=sd,computed=z),finer=fine,resolution_error=resolution_error),'06_coexistence_score_verification.rds')
cat('Analytic and increased-resolution checks passed.\n')
